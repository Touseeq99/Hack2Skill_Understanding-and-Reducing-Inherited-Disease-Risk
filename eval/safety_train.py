def _build():
    items = list(_BASE) + [(t, set()) for t in _BENIGN]
    # Light composition for diversity: polite prefixes/suffixes keep the label unchanged.
    prefixes = {"en": ["Hi, ", "Hello, ", "Excuse me, "], "ar": ["السلام عليكم، ", "مرحبا، ", "لو سمحت، "]}
    out = list(items)
    for i, (text, labels) in enumerate(items):
        lang = "ar" if any("؀" <= ch <= "ۿ" for ch in text) else "en"
        if i % 3 == 0:
            out.append((prefixes[lang][i % 3 if i % 3 < len(prefixes[lang]) else 0] + text[0].lower() + text[1:] if lang == "en" else prefixes[lang][0] + text, set(labels)))
    return out


TRAIN = _build()
